"""Markdown report for Spike S2. Deterministic: tests compare it to BUDGET.md."""
from __future__ import annotations

from dataclasses import replace

import budget as b

GIB = b.GIB


def md(headers: list[str], rows: list[list[str]]) -> str:
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(out)


def mb(x: float) -> str:
    return f"{x / 1e6:,.0f} MB" if x >= 1e7 else f"{x / 1e6:,.1f} MB"


def pct(x: float) -> str:
    return f"{x * 100:.1f}%"


def hrs(h: float) -> str:
    if h < 1:
        return f"{h * 60:.0f} min"
    if h < 48:
        return f"{h:.1f} h"
    return f"{h / 24:.1f} d"


def usd(x: float) -> str:
    if x >= 1000:
        return f"${x:,.0f}"
    if x >= 1:
        return f"${x:.2f}"
    return f"${x:.3f}"


def k(n: int) -> str:
    return f"{n // 1000}k"


def render_report() -> str:
    p = b.Params()
    limits = b.load_limits()
    bench = b.load_bench()
    meta = bench["meta"]
    q = limits["confluence_rest_quota"]
    prices = limits["forge_prices"]
    sql_limit = limits["forge_sql"]["stored_bytes_per_installation_production"]
    pool = q["tier1_global_pool_points_per_hour_per_app"]
    out: list[str] = []
    w = out.append

    w("# Spike S2: budget tables (generated)\n")
    w("Generated by `python tools/compute-budget/run.py --write`. **Do not edit by hand.** A test fails if this file is stale.\n")
    w("CPU per page is **MEASURED on the sandbox CPU, not on Forge hardware**; everything derived from it is **ESTIMATED**. Atlassian "
      "limits and prices are `ASSUMED (search-reported)`; see `limits.json`.\n")

    # CPU
    w("## 1. Measured fingerprint cost (sandbox)\n")
    w(f"Machine: {meta['cpu_model']}, {meta['cpu_count']} vCPU, Node {meta['node']}, {meta['platform']}. Pipeline per page: strip tags, "
      f"tokenize, {meta['shingle_words']}-word shingles, MinHash k={meta['k']}, {meta['bands']} bands x {meta['rows']} rows. Synthetic Zipf pages; "
      f"{meta['rounds']} timed rounds, median shown. `heavy` markup is about 28.8 B/word, `light` about 8.8 B/word.\n")
    rows = []
    for r in bench["fingerprint"]:
        rows.append([r["markup"], f"{r['words']:,}", f"{r['storage_bytes_per_page'] / 1000:,.1f} KB", f"{r['us_per_page_median']:,.0f} us",
                     f"{r['us_per_page_p10']:,.0f} to {r['us_per_page_p90']:,.0f} us", f"{r['us_per_word_median']:.2f}"])
    w(md(["Markup", "Words", "Storage-format size", "Median per page", "p10 to p90", "us per word"], rows))
    w("")
    sb = b.sandbox_us_per_page(p, bench)
    share = b.cpu_share(p.memory_mb, p.mb_per_vcpu)
    fg = b.forge_us_per_page(p, bench)
    w(f"Mix of {', '.join(f'{int(wt * 100)} % x {wd:,} words' for wd, wt in p.mix)} gives a mean of **{b.mean_words(p):,.0f} words**. "
      f"Mix-weighted cost on the sandbox: **{sb:,.0f} us per page**. At {p.memory_mb} MB the assumed CPU share is {share:.3f} of a vCPU "
      f"({p.mb_per_vcpu:,.0f} MB per vCPU), so the Forge estimate is **{fg:,.0f} us per page**, or **{fg * 50 / 1e6:.2f} s of CPU for a 50-page batch** "
      f"and **{fg * 50_000 / 1e6:.0f} s for a 50k-page tenant**.\n")

    # storage
    w("## 2. Forge SQL storage (G1)\n")
    w(f"Per page: signature {p.k} x {p.signature_bytes_per_hash} B = {p.k * p.signature_bytes_per_hash} B; {p.bands} band rows x {p.band_row_bytes} B = "
      f"{p.bands * p.band_row_bytes:,} B; metadata {p.meta_bytes} B; **{b.bytes_per_page(p):,} B per page**. Limit: "
      f"{sql_limit / GIB:.0f} GiB per production installation (search-reported).\n")
    rows = []
    for n in (10_000, 50_000, 250_000, 500_000):
        rows.append([k(n), mb(b.storage_bytes(p, n)), pct(b.storage_fraction(p, n, sql_limit))])
    w(md(["Pages", "Index size", "Share of SQL limit"], rows))
    w("")
    w(f"Largest tenant at 50 % of the limit: **{b.max_pages_within(p, 0.5, sql_limit):,} pages**; at the hard limit: {b.max_pages_within(p, 1.0, sql_limit):,}.\n")
    w("### Sensitivity to the one parameter that cannot be measured here: bytes per band row\n")
    rows = []
    for rb in (50, 70, 100, 150, 200):
        q2 = replace(p, band_row_bytes=rb)
        n250 = b.storage_fraction(q2, 250_000, sql_limit)
        rows.append([f"{rb} B", f"{b.bytes_per_page(q2):,} B", f"{b.max_pages_within(q2, 0.5, sql_limit):,}", f"{b.max_pages_within(q2, 1.0, sql_limit):,}",
                     pct(n250), "PASS" if n250 <= 0.5 else "FAIL"])
    w(md(["Band row size", "Per page", "N at 50 %", "N at 100 %", "250k share", "G1"], rows))
    w("")
    w("### Levers if the row size turns out larger\n")
    variants = [
        ("Baseline (k=128, 16 bands, 70 B rows)", p),
        ("8 bands instead of 16", replace(p, bands=8)),
        ("k=64, 8 bands", replace(p, k=64, bands=8)),
        ("Do not store signatures (recompute from text)", replace(p, signature_bytes_per_hash=0)),
        ("150 B rows, 8 bands, no stored signature", replace(p, band_row_bytes=150, bands=8, signature_bytes_per_hash=0)),
    ]
    rows = []
    for label, q2 in variants:
        rows.append([label, f"{b.bytes_per_page(q2):,} B", f"{b.max_pages_within(q2, 0.5, sql_limit):,}", pct(b.storage_fraction(q2, 250_000, sql_limit))])
    w(md(["Variant", "Per page", "N at 50 %", "250k share"], rows))
    w("")

    # memory
    w("## 3. In-memory LSH index, if one function held it all (reference)\n")
    w("Naive `Map<number, number[]>` per band is MEASURED (heap delta). Compact sorted typed arrays are 12 B per entry by construction "
      "(`process.memoryUsage().arrayBuffers` under-counts them, so the theoretical figure is shown).\n")
    rows = []
    for r in bench["lsh_index_memory"]:
        n = r["pages"]
        rows.append([k(n), f"{r['entries']:,}", f"{r['naive_map_heap_mb']:,.0f} MB", f"{b.compact_index_bytes(p, n) / 1048576:,.0f} MB",
                     f"{r['naive_build_ms'] / 1000:.1f} s / {r['compact_build_ms'] / 1000:.1f} s"])
    w(md(["Pages", "Band entries", "Naive Map (measured)", "Compact (12 B each)", "Build time naive / compact"], rows))
    w("")
    w("Function memory is 512 MB by default and up to 1,024 MB documented (the manifest schema's own maximum is 4,096, which "
      "contradicts its description). A naive index for 250k pages (386 MB) would use about three quarters of the 512 MB default and leave "
      "little headroom; the compact one (46 MB) fits easily. State must live in SQL anyway, because a function does not keep memory "
      "between invocations.\n")

    # batch time
    w("## 4. Time per batch (G2)\n")
    rows = []
    for n in (50, 250):
        t = b.batch_seconds(p, bench, n)
        rows.append([f"{n}", f"{t['fetch']:.1f} s", f"{t['cpu']:.2f} s", f"{t['sql']:.2f} s", f"**{t['total']:.1f} s**",
                     f"{900 / t['total']:.0f}x", "yes" if t["total"] <= 55 else "no"])
    w(md(["Pages per batch", "REST fetch", "CPU", "SQL writes", "Total", "Headroom vs 900 s", "Fits 55 s default"], rows))
    w("")
    w(f"Fetch is {p.pages_per_request} pages per request at {p.request_seconds:g} s (ASSUMED). CPU is {fg:,.0f} us per page. SQL is "
      f"{b.rows_per_page(p)} rows per page in {p.rows_per_statement}-row statements at {p.statement_seconds} s each (ASSUMED).\n")

    # quota
    w("## 5. Confluence REST quota and scan time (G3)\n")
    w(f"Search-reported rule: 1 base point per request plus 1 point per core object (page); writes cost the base only. Tier 1 is "
      f"**{pool:,} points per hour for the whole app, shared by all tenants**. Tier 2 per-tenant pools exist only after Atlassian review "
      f"(Standard: {q['tier2_per_tenant_standard']['base_points_per_hour']:,} + {q['tier2_per_tenant_standard']['points_per_user_per_hour']} per user per hour).\n")
    rows = []
    for n in (10_000, 50_000, 250_000):
        pts = b.scan_points(n, p.pages_per_request)
        t2 = b.tier2_pool_per_hour(q["tier2_per_tenant_standard"]["base_points_per_hour"], q["tier2_per_tenant_standard"]["points_per_user_per_hour"], p.users)
        rows.append([k(n), f"{pts:,}", pct(pts / pool), hrs(b.scan_hours(pts, pool, 1.0)), hrs(b.scan_hours(pts, pool, 0.2)),
                     hrs(b.scan_hours(pts, pool, 0.05)), hrs(b.scan_hours(pts, t2, 1.0)), f"{b.compute_bound_hours(p, bench, n) * 60:.1f} min"])
    w(md(["Pages", "Points for one scan", "Share of one hour's Tier 1 pool", "Tier 1 at 100 %", "at 20 %", "at 5 %", f"Tier 2 Standard, {p.users:,} users", "Consumers alone"], rows))
    w("")
    rows = []
    for share in (1.0, 0.2, 0.05):
        rows.append([f"{int(share * 100)} %", f"{b.tenants_onboarded_per_day(50_000, pool, share):.1f}", f"{b.tenants_onboarded_per_day(250_000, pool, share):.1f}"])
    w("Full first scans the **app-wide Tier 1 pool can complete per day**, if it did nothing else:\n")
    w(md(["Share of pool", "50k-page tenants / day", "250k-page tenants / day"], rows))
    w("")
    w("Steady-state edit traffic on the same pool (ASSUMED: 5 % of pages edited per month, 8 points per edit: changed page, previous version, two partner pages):\n")
    rows = []
    for tenants in (10, 100, 1000, 2000):
        pph = b.steady_points_per_hour(tenants, 50_000, p.monthly_edit_rate, 8)
        rows.append([f"{tenants:,}", f"{pph:,.0f}", pct(pph / pool)])
    w(md(["Tenants (50k pages each)", "Points per hour", "Share of Tier 1 pool"], rows))
    w("")

    # fan-out
    w("## 6. Async-event fan-out\n")
    ev = limits["async_events"]
    rows = []
    for n in (50_000, 250_000):
        e1 = b.events_needed(n, 1)
        e50 = b.events_needed(n, ev["events_per_push_max"])
        rows.append([k(n), f"{e1:,}", hrs(b.push_minutes(e1, ev["events_pushed_per_minute_max"]) / 60), f"{e50:,}", hrs(b.push_minutes(e50, ev["events_pushed_per_minute_max"]) / 60)])
    w(md(["Pages", "Events at 1 page each", "Push time at 500/min", "Events at 50 pages each", "Push time at 500/min"], rows))
    w("")
    w(f"Search-reported limits: at most {ev['events_per_push_max']} events and {ev['combined_payload_kb_max']} KB per push, {ev['events_pushed_per_minute_max']} events per minute. "
      "One event per page would take hours to enqueue at 50k pages, so Architecture X chains **cursors**: each consumer fetches the next batch "
      "(bodies arrive in the list response), processes it and pushes the next cursor.\n")

    # cost
    w("## 7. Forge platform cost for the classical pipeline (G4)\n")
    rows = []
    for n in (10_000, 50_000, 250_000):
        no_free = b.steady_state_monthly(p, prices, n, free=False)
        free = b.steady_state_monthly(p, prices, n, free=True)
        bf = b.backfill_one_time(p, bench, prices, n)
        rows.append([k(n), f"{no_free['edits']:,.0f}", usd(no_free["functions"]), usd(no_free["sql_storage"]), usd(no_free["sql_compute"]),
                     usd(no_free["sql_requests"]), f"**{usd(no_free['total'])}**", usd(free["total"]), usd(bf["total"])])
    w(md(["Pages", "Edits / month", "Functions", "SQL storage", "SQL compute", "SQL requests", "Total, no free allowance", "Total with free allowance", "One-time backfill"], rows))
    w("")
    w("Free allowances are shown for reference only; whether they are per app or per installation is not stated in the summary.\n")

    # containers
    w("## 8. Reference: Forge Containers (Preview) reservation cost\n")
    c = limits["containers"]
    rows = []
    for vcpu, gib in ((0.25, 0.5), (0.5, 1.0), (1.0, 2.0)):
        one = b.containers_monthly(vcpu, gib, c)
        rows.append([f"{vcpu:g} vCPU / {gib:g} GiB", usd(one), usd(one * 3)])
    w(md(["Service size", "Per instance per month", "Three regions"], rows))
    w("")
    w(f"Reservation-based: billed whether or not requests arrive. Maximum per service {c['max_cpu_millis']}m CPU and {c['max_memory_mib']} MiB "
      "(search-reported). Whether a service is per app or per tenant is not stated in the summary. Not needed by Architecture X.\n")

    # criteria
    w("## 9. Pre-registered criteria\n")
    res = b.evaluate(p, limits, bench)
    w(md(["ID", "Criterion", "Result", "Verdict"], [[r["id"], r["text"], r["result"], "PASS" if r["pass"] else "FAIL"] for r in res]))
    w("")
    w(f"**GATE-S2 sentence:** {b.gate_sentence(p, limits)}.\n")
    return "\n".join(out) + "\n"
