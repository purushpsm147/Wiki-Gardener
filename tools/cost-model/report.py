"""Markdown sensitivity report for Spike S1. Deterministic: tests compare it to SENSITIVITY.md."""
from __future__ import annotations

from dataclasses import replace

import cost_model as cm

PAGES = [10_000, 50_000, 250_000]
YIELDS = [0.001, 0.005, 0.02]
USERS = [100, 250, 1_000, 5_000]
PRICES_PER_USER = [0.25, 0.50, 1.00, 2.00, 4.00]
CHURNS = [0.05, 0.20, 0.50, 1.00]


def usd(x: float) -> str:
    if x == float("inf"):
        return "∞"
    if x >= 1000:
        return f"${x:,.0f}"
    if x >= 10:
        return f"${x:,.2f}"
    if x >= 1:
        return f"${x:.2f}"
    if x >= 0.01:
        return f"${x:.3f}"
    return f"${x:.4f}"


def pct(x: float) -> str:
    if x == float("inf"):
        return "∞"
    p = x * 100
    if p >= 1000:
        return ">1000%"
    if p >= 10:
        return f"{p:.0f}%"
    if p >= 1:
        return f"{p:.1f}%"
    if p < 0.01:
        return "<0.01%"
    return f"{p:.2f}%"


def margin_pct(x: float) -> str:
    """Margins sit near 100 %, so show two decimals instead of rounding the interesting part away."""
    return f"{x * 100:.2f}%"


def hours(minutes: float) -> str:
    h = minutes / 60
    if h < 1:
        return f"{minutes:.0f} min"
    if h < 48:
        return f"{h:.1f} h"
    return f"{h / 24:.1f} d"


def md(headers: list[str], rows: list[list[str]]) -> str:
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(out)


def yl(y: float) -> str:
    return f"{y * 100:g}%"


def pl(p: int) -> str:
    return f"{p // 1000}k"


# ---- pre-registered scenarios (written into the spike doc BEFORE the model was run) --------------------------


def base(models: dict[str, cm.ModelPrice]) -> cm.Scenario:
    return cm.Scenario(
        pages=50_000, yield_rate=0.005, profile=cm.PROFILES["T2"], model=models["sonnet-4.5"],
        monthly_churn=0.20, users=1_000, price_per_user=1.00, take_rate=0.17,
    )


def k2(models: dict[str, cm.ModelPrice]) -> cm.Scenario:
    """Page-heavy, user-light tenant with a looser funnel."""
    return replace(base(models), yield_rate=0.02, profile=cm.PROFILES["T3"], users=250, price_per_user=0.50)


def k3(models: dict[str, cm.ModelPrice]) -> cm.Scenario:
    """Stress: loose funnel, whole-page prompts, the most expensive model, everything re-judged monthly."""
    return replace(
        base(models), yield_rate=0.02, profile=cm.PROFILES["T4"], model=models["opus-4.6"],
        monthly_churn=1.00, users=250, price_per_user=0.50,
    )


def render_report() -> str:
    prices = cm.load_prices()
    models = cm.load_models()
    lim = prices["forge_llm_limits"]
    b = base(models)
    out: list[str] = []
    w = out.append

    w("# Spike S1: sensitivity tables (generated)\n")
    w("Generated by `python tools/cost-model/run.py --write`. **Do not edit by hand.** A test fails if this file is stale.\n")
    w("All Atlassian prices below are `ASSUMED (search-reported)`; see `prices.json` for the source and grade of each.\n")

    w("## Pre-registered base case\n")
    w(md(["Parameter", "Value", "Grade"], [
        ["Pages", f"{b.pages:,}", "brief"],
        ["Funnel yield (candidate pairs per page)", yl(b.yield_rate), "brief (0.1 / 0.5 / 2 %); reading ASSUMED"],
        ["Candidate pairs", f"{b.candidate_pairs:,}", "derived"],
        ["Tokens per call (in / out)", f"{b.profile.input_tokens:,} / {b.profile.output_tokens:,} ({b.profile.key})", "ASSUMED"],
        ["Model and price (in / out per 1M tokens)", f"{b.model.label}: ${b.model.input_per_mtok:g} / ${b.model.output_per_mtok:g}", b.model.evidence],
        ["Calls per pair", f"{b.calls_per_pair:g}", "ASSUMED"],
        ["Monthly churn (pairs re-judged; ADR-005 cache covers the rest)", yl(b.monthly_churn), "ASSUMED"],
        ["Forge wait per call / memory", f"{b.llm_call_seconds:g} s / {b.function_memory_gb:g} GB", "ASSUMED"],
        ["Users / price per user per month", f"{b.users:,} / ${b.price_per_user:.2f}", "ASSUMED (price grid; no verified comparable)"],
        ["Atlassian take rate", yl(b.take_rate), "ASSUMED (search-reported rate, interpretation ASSUMED)"],
    ]))
    w("")

    # A
    w("## A. One-time backfill LLM cost (base token profile and model)\n")
    rows = []
    for p in PAGES:
        row = [pl(p)]
        for y in YIELDS:
            s = replace(b, pages=p, yield_rate=y)
            row.append(f"{usd(cm.backfill_llm_cost(s))} ({s.candidate_pairs:,} pairs)")
        rows.append(row)
    w(md(["Pages \\ yield"] + [yl(y) for y in YIELDS], rows))
    w("")

    # B
    w("## B. Steady-state monthly LLM cost (base profile and model, 20 % monthly churn)\n")
    rows = []
    for p in PAGES:
        row = [pl(p)]
        for y in YIELDS:
            s = replace(b, pages=p, yield_rate=y)
            row.append(usd(cm.monthly_llm_cost(s)))
        rows.append(row)
    w(md(["Pages \\ yield"] + [yl(y) for y in YIELDS], rows))
    w("")

    # C
    for n, y in ((1, 0.005), (2, 0.02)):
        w(f"## C{n}. 50k pages, yield {yl(y)}: monthly LLM cost by model and token profile (20 % churn)\n")
        rows = []
        for mk in ("haiku-4.5", "sonnet-5", "sonnet-4.5", "opus-4.6"):
            row = [f"{models[mk].label} (${models[mk].input_per_mtok:g}/${models[mk].output_per_mtok:g})"]
            for pk in ("T1", "T2", "T3", "T4"):
                s = replace(b, yield_rate=y, model=models[mk], profile=cm.PROFILES[pk])
                row.append(usd(cm.monthly_llm_cost(s)))
            rows.append(row)
        w(md(["Model"] + [f"{k}: {cm.PROFILES[k].input_tokens:,}/{cm.PROFILES[k].output_tokens:,}" for k in ("T1", "T2", "T3", "T4")], rows))
        w("")

    # D
    w("## D. Churn sensitivity (50k pages, base yield, profile and model, 1,000 users at $1.00)\n")
    rows = []
    for c in CHURNS:
        s = replace(b, monthly_churn=c)
        rows.append([yl(c), f"{cm.monthly_calls(s):,.0f}", usd(cm.monthly_llm_cost(s)), pct(cm.llm_share_of_net(s))])
    w(md(["Monthly churn", "Verdict calls / month", "LLM cost / month", "Share of net revenue"], rows))
    w("")

    # E
    def share_grid(s0: cm.Scenario, title: str) -> None:
        w(f"## {title}\n")
        w(f"Monthly LLM cost held at **{usd(cm.monthly_llm_cost(s0))}**. Cells over {pct(cm.KILL_THRESHOLD)} are **bold**.\n")
        rows = []
        for u in USERS:
            row = [f"{u:,}"]
            for pr in PRICES_PER_USER:
                s = replace(s0, users=u, price_per_user=pr)
                v = cm.llm_share_of_net(s)
                row.append(f"**{pct(v)}**" if v > cm.KILL_THRESHOLD else pct(v))
            rows.append(row)
        w(md(["Users \\ $/user/month"] + [f"${p:.2f}" for p in PRICES_PER_USER], rows))
        w("")

    share_grid(b, "E1. LLM cost as a share of net revenue: base cost, revenue grid")
    share_grid(replace(b, yield_rate=0.02, profile=cm.PROFILES["T3"]), "E2. Same grid with a looser funnel (2 % yield) and section-level prompts (T3)")
    share_grid(k3(models), "E3. Same grid under the stress cost (K3: 2 % yield, T4, Opus 4.6, full monthly re-judgement)")

    # I
    w("## I. If 'yield' means each flagged page brings several partners (pair_multiplier)\n")
    w("Base cost and revenue; 50k pages at 0.5 % yield.\n")
    rows = []
    for k in (1, 5, 20, 100):
        s = replace(b, pair_multiplier=float(k))
        rows.append([f"x{k}", f"{s.candidate_pairs:,}", usd(cm.backfill_llm_cost(s)), usd(cm.monthly_llm_cost(s)), pct(cm.llm_share_of_net(s))])
    w(md(["Pairs per flagged page", "Candidate pairs", "Backfill cost", "LLM cost / month", "Share of net revenue"], rows))
    w("")

    # F
    w("## F. Break-even: net monthly revenue needed for LLM cost to stay under 30 %\n")
    rows = []
    for p in PAGES:
        row = [pl(p)]
        for y in YIELDS:
            s = replace(b, pages=p, yield_rate=y)
            row.append(usd(cm.breakeven_net_revenue(s)))
        rows.append(row)
    w(md(["Pages \\ yield"] + [yl(y) for y in YIELDS], rows))
    w("")
    mp = cm.max_pairs_within_budget(b)
    w(f"At base revenue ({usd(cm.net_revenue(b))}/month net) the funnel could pass **{mp:,.0f} candidate pairs** "
      f"({mp / b.pages:.1f} per page) before LLM cost reaches 30 %: about **{mp / b.candidate_pairs:,.0f}x** the base-case {b.candidate_pairs:,}.\n")

    # G
    w(f"## G. Backfill wall-clock under Forge LLM limits ({lim['requests_per_minute']} req/min, "
      f"{lim['tokens_per_minute_per_installation_per_model']:,} tokens/min per installation per model; base profile)\n")
    rows = []
    for p in PAGES:
        row = [pl(p)]
        for y in YIELDS:
            s = replace(b, pages=p, yield_rate=y)
            row.append(hours(cm.backfill_minutes(s, lim["tokens_per_minute_per_installation_per_model"], lim["requests_per_minute"])))
        rows.append(row)
    w(md(["Pages \\ yield"] + [yl(y) for y in YIELDS], rows))
    w("")

    # H
    w("## H. Gross margin on the LLM stage (LLM + Forge wait compute only; 1,000 users at $1.00)\n")
    cases = [
        ("Base: Sonnet 4.5, T2", b),
        ("Cheap: Haiku 4.5, T1 (A3-shaped prompts)", replace(b, model=models["haiku-4.5"], profile=cm.PROFILES["T1"])),
        ("Stress K3 cost, base revenue", replace(k3(models), users=1_000, price_per_user=1.00)),
    ]
    rows = []
    for label, s in cases:
        for take, tl in ((0.17, "17 % take"), (0.0, "0 % take (Runs on Atlassian, first $1M)")):
            s2 = replace(s, take_rate=take)
            rows.append([label, tl, usd(cm.net_revenue(s2)), usd(cm.monthly_llm_cost(s2)), usd(cm.monthly_compute_cost(s2)), margin_pct(cm.gross_margin(s2))])
    rows.append(["LLM-free (A3 detector only)", "17 % take", usd(cm.net_revenue(b)), "$0", "n/a (see S2)", "100% of this stage"])
    w(md(["Case", "Atlassian take", "Net revenue / month", "LLM / month", "Forge wait compute / month", "Margin on this stage"], rows))
    w("")
    w(f"Value of the Runs-on-Atlassian revenue window, ASSUMED reading: 17 % x $1,000,000 lifetime Forge revenue = **{usd(0.17 * 1_000_000)}**.\n")

    # criteria
    w("## Pre-registered criteria and results\n")
    k1, k2s, k3s = b, k2(models), k3(models)
    tpm, rpm = lim["tokens_per_minute_per_installation_per_model"], lim["requests_per_minute"]
    bf = cm.backfill_minutes(b, tpm, rpm)
    rows = [
        ["K1", "Base case: steady-state LLM cost is at most 30 % of net revenue", pct(cm.llm_share_of_net(k1)), "PASS" if not cm.exceeds_threshold(k1) else "FAIL"],
        ["K2", "Page-heavy, user-light (250 users at $0.50; 2 % yield; T3): at most 30 %", pct(cm.llm_share_of_net(k2s)), "PASS" if not cm.exceeds_threshold(k2s) else "FAIL"],
        ["K3", "Stress (250 users at $0.50; 2 % yield; T4; Opus 4.6; 100 % churn): at most 30 %", pct(cm.llm_share_of_net(k3s)), "PASS" if not cm.exceeds_threshold(k3s) else "FAIL"],
        ["K4", "50k-page backfill finishes within 24 h under the Forge LLM limits (base)", hours(bf), "PASS" if bf <= 24 * 60 else "FAIL"],
    ]
    w(md(["ID", "Criterion", "Result", "Verdict"], rows))
    w("")
    return "\n".join(out) + "\n"
